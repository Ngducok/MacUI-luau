import { globSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const workspace = resolve(dirname(fileURLToPath(import.meta.url)), "..");

export function bundle(root) {
  const files = globSync("**/*.luau", { cwd: root }).sort();
  const modules = files.map((file) => ({
    id: file
      .replaceAll("\\", "/")
      .replace(/\.luau$/, "")
      .replace(/(^|\/)init$/, ""),
    source: readFileSync(join(root, file), "utf8").replace(/\r\n/g, "\n"),
  }));
  if (!modules.some((module) => module.id === ""))
    throw new Error("Missing init.luau");
  if (new Set(modules.map((module) => module.id)).size !== modules.length)
    throw new Error("Duplicate module path");
  const paths = new Set();
  for (const { id } of modules) {
    const parts = id.split("/");
    for (let i = 1; id && i <= parts.length; i++)
      paths.add(parts.slice(0, i).join("/"));
  }
  const nodes = [...paths].sort(
    (a, b) => a.split("/").length - b.split("/").length || a.localeCompare(b),
  );
  return `-- MacUI | https://github.com/Ngducok/MacUI-luau
-- Generated by tools/build.mjs. Edit src/shared/UILibrary, then rebuild.
local nodes = { [""] = { Name = "MacUI" } }
for _, path in { ${nodes.map(JSON.stringify).join(", ")} } do
    local parent, name = string.match(path, "^(.*)/([^/]+)$")
    if not name then parent, name = "", path end
    local node = { Name = name, Parent = nodes[parent] }
    nodes[path] = node
    node.Parent[name] = node
end
local loaders, cache, loading = {}, {}, {}
${modules.map(({ id, source }) => `\n-- ${id || "init"}\nloaders[nodes[${JSON.stringify(id)}]] = function(script, require)\n${source}\nend`).join("\n")}
local function load(module)
    if cache[module] ~= nil then return cache[module] end
    assert(loaders[module], "MacUI: unknown module")
    assert(not loading[module], "MacUI: circular module dependency")
    loading[module] = true
    local ok, value = pcall(loaders[module], module, load)
    loading[module] = nil
    if not ok then error("MacUI / " .. module.Name .. ": " .. tostring(value), 2) end
    cache[module] = value
    return value
end
local MacUI = load(nodes[""])
local createWindow = MacUI.CreateWindow
function MacUI:CreateWindow(options)
    options = table.clone(options or {})
    if not options.Parent and type(gethui) == "function" then
        local ok, parent = pcall(gethui)
        if ok and typeof(parent) == "Instance" then options.Parent = parent end
    end
    return createWindow(self, options)
end
return MacUI
`;
}

if (
  process.argv[1] &&
  resolve(process.argv[1]) === fileURLToPath(import.meta.url)
) {
  const output = join(workspace, "dist/MacUI.luau");
  mkdirSync(dirname(output), { recursive: true });
  writeFileSync(output, bundle(join(workspace, "src/shared/UILibrary")));
  console.log("Built dist/MacUI.luau");
}
